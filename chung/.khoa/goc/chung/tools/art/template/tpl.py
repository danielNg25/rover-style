"""Shared code of the character TEMPLATE tools (tools/art/template/*.py). Not a command.

One template = one JSON (human-v1.json, extra-v1.json) that holds
  slots     where each piece sits on the 1536 x 1024 sheet (box), at which scale it is drawn, where the
            grey mannequin's piece is (tpl), where that piece stands on the 400 x 560 character canvas
            (canvas), how generated art is put there (anchor, fit) and the joints inside the slot (pivots);
  pieces    the rig pieces built from the slots (side, mirror, pivot on the canvas, parent, stacking z).
The SAME placement rule lives in src/puppet/template/fromTemplate.ts (function place); keep the two alike.
"""
import json
import os
import sys

import numpy as np
from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import common as C  # noqa: E402

FIT_CLAMP = (0.8, 1.25)
DEFAULT = 'human-v2'
BUILDS = ['adult', 'child', 'heavy', 'tall']                       # keys of BUILDS in src/puppet/template/fromTemplate.ts
EXPRESSIONS = ['neutral', 'pleased', 'angry', 'sad', 'surprised', 'doubtful', 'smug', 'afraid']


def template_of(sheet):
    """Name of the template a sheet was generated on: the layout image in SHEET.prov.json (written by gen.sh), or the
    sheet itself when it is a template; else the current default."""
    names = [f[:-5] for f in os.listdir(HERE) if f.endswith('.json')]
    base = os.path.basename(sheet)[:-4]
    if os.path.dirname(os.path.abspath(sheet)) == HERE and base in names:
        return base
    try:
        for r in json.load(open(sheet + '.prov.json')).get('refs', []):
            b = os.path.basename(r['path'])[:-4]
            if b in names:
                return b
    except (OSError, ValueError, KeyError):
        pass
    return DEFAULT


def write_models():
    """src/puppet/template/models.gen.ts: every rig module that slice.py wrote under src/chars/_lib, so each character
    gets its model-sheet stills (src/demo/TemplateDemo.tsx) without anyone editing a shared file by hand."""
    import re
    lib = os.path.join(C.ROOT, 'src', 'chars', '_lib')
    rows = []
    for f in sorted(os.listdir(lib)):
        if not f.endswith('.ts'):
            continue
        head = open(os.path.join(lib, f)).read(4000)
        m = re.search(r'export const (\w+)_MANIFEST: Manifest', head)
        if head.startswith('// GENERATED by tools/art/template/slice.py') and m and "import {fromTemplate}" in head:
            rows.append((m.group(1), f[:-3]))
    out = ['// GENERATED by tools/art/template/slice.py (tpl.write_models): the characters cut from a template sheet. Do not edit.',
           "import type {PuppetRig} from '../types';", "import type {Manifest} from './types';"]
    out += [f"import {{{c}, {c}_MANIFEST}} from '../../chars/_lib/{f}';" for c, f in rows]
    out.append('export const MODELS: {id: string; rig: PuppetRig; manifest: Manifest}[] = [')
    out += [f'  {{id: {c}_MANIFEST.id, rig: {c}, manifest: {c}_MANIFEST}},' for c, f in rows]
    out.append('];')
    open(os.path.join(C.ROOT, 'src', 'puppet', 'template', 'models.gen.ts'), 'w').write('\n'.join(out) + '\n')
    return len(rows)


def load(name_or_path):
    p = name_or_path if name_or_path.endswith('.json') else os.path.join(HERE, name_or_path + '.json')
    return json.load(open(p))


def soft_alpha(rgb, key):
    """Alpha of a sheet exactly as tools/art/cut.py makes it (qa.json art.cut)."""
    t = C.cfg('cut')
    d = C.dist(rgb, key)
    soft = np.clip((d - t['alpha_lo']) / (t['alpha_hi'] - t['alpha_lo']), 0, 1)
    soft = np.asarray(Image.fromarray((soft * 255).astype('uint8')).filter(ImageFilter.GaussianBlur(t['alpha_blur']))).astype(float)
    return d, soft


def place(slot, art, adjust=None):
    """Canvas rect [x, y, w, h] of a cut piece (screen-left / centre instance).
    art = tight bbox of the art on the sheet [x0, y0, x1, y1]; adjust = {dx, dy, scale} typed by hand in the manifest."""
    adjust = adjust or {}
    s = slot['scale']
    tx0, ty0, tx1, ty1 = slot['tpl']
    cx, cy, cw, ch = slot['canvas']
    bw, bh = art[2] - art[0], art[3] - art[1]
    k = 1.0
    if slot['fit'] == 'h':
        k = (ty1 - ty0) / bh
    elif slot['fit'] == 'w':
        k = (tx1 - tx0) / bw
    k = min(FIT_CLAMP[1], max(FIT_CLAMP[0], k)) * adjust.get('scale', 1)
    w, h = bw / s * k, bh / s * k
    ax, ay = slot['anchor']
    x = cx + cw / 2 - w / 2 if ax == 'c' else cx + (art[0] - tx0) / s
    y = cy if ay == 't' else cy + ch - h if ay == 'b' else cy + ch / 2 - h / 2 if ay == 'c' else cy + (art[1] - ty0) / s
    return [x + adjust.get('dx', 0), y + adjust.get('dy', 0), w, h]


def assemble(T, get, view='front', pick=None, zoom=2, bg=(232, 228, 218), adjust=None, lids=False):
    """Draw the figure from cut pieces by the template's own map. get(slot) -> (RGBA PIL image cropped to the art's
    tight bbox, art bbox on the sheet) or None for a missing optional slot. pick = {group: option} for the swap groups."""
    pick = {**{g: v['default'] for g, v in T.get('groups', {}).items()}, **(pick or {})}
    W, H = T['canvas']
    out = Image.new('RGBA', (W * zoom, H * zoom), bg + (255,))
    cx = T['centerX']
    for p in sorted([p for p in T['pieces'] if p.get('view', 'front') in (view, 'both')], key=lambda p: p['z']):
        if p.get('group') and pick.get(p['group']) != p['option']:
            continue
        if p['slot'] == 'lid' and not lids:  # the lid rests shut over the eye; an open eye hides it
            continue
        got = get(p['slot'])
        if got is None:
            continue
        im, art = got
        x, y, w, h = place(T['slots'][p['slot']], art, (adjust or {}).get(p['slot']))
        if p.get('mirror'):
            x = 2 * cx - x - w
            im = im.transpose(Image.FLIP_LEFT_RIGHT)
        im = im.resize((max(1, round(w * zoom)), max(1, round(h * zoom))), Image.LANCZOS)
        out.alpha_composite(im, (round(x * zoom), round(y * zoom)))
    return out


def sheet_getter(T, sheet_rgb, key=None):
    """get() for assemble(): cut the mannequin's pieces straight from a template sheet by the tpl boxes."""
    key = C.parse_colour(T['key']) if key is None else key
    _, soft = soft_alpha(sheet_rgb, key)

    def get(slot):
        x0, y0, x1, y1 = T['slots'][slot]['tpl']
        rgba = np.dstack([sheet_rgb[y0:y1, x0:x1], soft[y0:y1, x0:x1]]).astype('uint8')
        import spill as S
        rgba = S.despill(rgba, key, C.cfg('spill'))
        return Image.fromarray(rgba), [x0, y0, x1, y1]
    return get
